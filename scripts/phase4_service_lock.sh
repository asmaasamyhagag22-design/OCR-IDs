#!/bin/bash
# Phase 4 OCR service: requirements-linux.txt from the stage-1 WSL venv's exact pins.
#   wsl -d Ubuntu -e bash scripts/phase4_service_lock.sh
# Every pin of ~/venvs/ocrid-py3119 (pip itself excluded: it is the installer),
# plus the service stack resolved against those pins as constraints (D-041).
# No dependency resolution happens here: --no-deps keeps exactly this list.
# No hashes are written: sha256 hex text collides with the repository privacy
# scan's short-token rule, and that scan is not worked around (D-047).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UV="$HOME/.local/bin/uv"
WORK="$(mktemp -d)"
"$HOME/venvs/ocrid-py3119/bin/pip" freeze --all | grep -v -i '^pip==' > "$WORK/frozen.txt"
cat "$WORK/frozen.txt" - > "$WORK/requirements-linux.in" <<'EOF'
annotated-doc==0.0.5
fastapi==0.141.1
python-multipart==0.0.32
starlette==1.7.0
uvicorn==0.54.0
EOF
"$UV" pip compile "$WORK/requirements-linux.in" --no-deps \
  --python-version 3.11 --python-platform x86_64-manylinux_2_28 \
  --no-header --no-annotate --quiet -o "$WORK/requirements-linux.txt"
{
  echo "# Linux lock for the Fixed14 OCR service image (python 3.11.9, x86_64 manylinux)."
  echo "# Generated by scripts/phase4_service_lock.sh from ~/venvs/ocrid-py3119's exact pins"
  echo "# (pip excluded; tensorflow-intel is the only Windows-only package and is not here),"
  echo "# plus the service stack (D-041). Install with:"
  echo "#   pip install --no-deps -r requirements-linux.txt"
  echo "# then force-reinstall opencv-python-headless (see the Dockerfile): the frozen venv's"
  echo "# cv2 binary is the headless build (D-046)."
  cat "$WORK/requirements-linux.txt"
} > "$ROOT/requirements-linux.txt"
# the headless OpenCV entry alone, for the final force-reinstall (D-046)
grep '^opencv-python-headless==' "$ROOT/requirements-linux.txt" > "$ROOT/requirements-linux-opencv-headless.txt"
wc -l "$WORK/requirements-linux.in"
grep -c '==' "$ROOT/requirements-linux.txt"
rm -rf "$WORK"
